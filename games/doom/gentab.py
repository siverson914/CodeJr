#!/usr/bin/env python3
"""Generates tables.c for JRDOOM: integer tables only, so the 8088 never
touches floating point. Run by build.sh."""
import math, random

VIEW_COLS = 80
PLANE = 0.66          # tan(half FOV): about 67 degrees across
out = []
out.append("/* Generated by gentab.py. Do not edit. */")
out.append("const int sin_t[1024] = {")
v = [int(round(math.sin(i * 2 * math.pi / 1024) * 16384)) for i in range(1024)]
for i in range(0, 1024, 16):
    out.append("  " + ",".join(str(x) for x in v[i:i+16]) + ",")
out.append("};")
# atan table for angle-to-target: atan(i/64) for i in 0..64, in 1024ths
out.append("const unsigned char atan_tab[65] = {")
out.append("  " + ",".join(str(int(round(math.atan(i / 64) * 1024 / (2 * math.pi)))) for i in range(65)))
out.append("};")
random.seed(1993)
out.append("const unsigned char rnd_tab[256] = {")
r = list(range(256)); random.shuffle(r)
for i in range(0, 256, 32):
    out.append("  " + ",".join(str(x) for x in r[i:i+32]) + ",")
out.append("};")
open("tables.c", "w").write("\n".join(out) + "\n")
