#!/usr/bin/env python3
"""Generates speech.c: robot voice phrases for the SN76496's volume register.

Each phrase is rendered by SAM (say.cjs, needs node and sam-js), resampled to
RATE Hz, and stored as 4-bit attenuation values (0 = loudest, 15 = off), two
per byte, high nibble first. The PCjr plays them by holding tone voice 0 at
an inaudible pitch and writing one attenuation per sample (see music.c).
Run: NODE_PATH=<dir with node_modules> python3 genspeech.py
"""
import math, os, subprocess, tempfile

RATE = 6000
PHRASES = [  # (C name, text for SAM, speed, pitch)
    ("sp_hello", "HELLO, P C JUNIOR.", 72, 64),
    ("sp_wait", "I HAVE BEEN WAITING FOR YOU, FOR FORTY TWO YEARS.", 76, 60),
    ("sp_friends", "FRIENDS, FOREVER.", 80, 56),
]
# amplitude of each attenuation step (2 dB per step), 15 = silent
AMP = [10 ** (-k / 10) for k in range(15)] + [0.0]


def render(text, speed, pitch):
    with tempfile.TemporaryDirectory() as d:
        p = os.path.join(d, "s.raw")
        subprocess.run(["node", "say.cjs", text, p, str(speed), str(pitch)], check=True)
        return open(p, "rb").read()


def resample(raw, src=22050):
    out = []
    step = src / RATE
    n = int(len(raw) / step)
    for i in range(n):
        a, b = int(i * step), int((i + 1) * step)
        seg = raw[a:max(b, a + 1)]
        out.append(sum(seg) / len(seg))
    return out


def to_att(samples):
    lo, hi = min(samples), max(samples)
    res = []
    for s in samples:
        v = (s - lo) / (hi - lo)
        res.append(min(range(16), key=lambda k: abs(AMP[k] - v)))
    # trim silence (att 15 or the resting level) from the ends
    rest = res[0]
    while res and res[-1] == rest:
        res.pop()
    return res


def main():
    out = ["/* Generated by genspeech.py: SAM robot voice, %d Hz, 4-bit SN76496 attenuation,\n"
           " * two samples per byte (high nibble first). Do not edit. */\n" % RATE,
           '#include "jrai.h"\n\n']
    for name, text, speed, pitch in PHRASES:
        att = to_att(resample(render(text, speed, pitch)))
        if len(att) & 1:
            att.append(15)
        data = bytes((att[i] << 4) | att[i + 1] for i in range(0, len(att), 2))
        out.append("/* \"%s\" */\nstatic const unsigned char far %s_d[%d] = {\n" % (text, name, len(data)))
        for i in range(0, len(data), 24):
            out.append("\t" + ",".join(str(b) for b in data[i:i + 24]) + ",\n")
        out.append("};\nconst speech %s = { %s_d, %du };\n\n" % (name, name, len(att)))
        print(f"{name}: {len(att) / RATE:.2f} s, {len(data)} bytes")
    open("speech.c", "w").write("".join(out))


if __name__ == "__main__":
    main()
