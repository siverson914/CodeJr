#!/usr/bin/env python3
"""Generates sintab.h: a 1024-entry sine table in 1.14 fixed point.
Run at development time only; the game itself never touches floating point."""
import math
vals = [round(math.sin(i * 2 * math.pi / 1024) * 16384) for i in range(1024)]
with open("sintab.h", "w") as f:
    f.write("/* Generated by gentab.py: sin(i*2pi/1024) * 16384 */\n")
    f.write("const int sintab[1024] = {\n")
    for i in range(0, 1024, 12):
        f.write("  " + ",".join(str(v) for v in vals[i:i+12]) + ",\n")
    f.write("};\n")
