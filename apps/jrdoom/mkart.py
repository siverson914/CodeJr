#!/usr/bin/env python3
"""Converts art.txt into artdata.c (run-length encoded columns, so the 8088
draws a scaled sprite or wall column as a few solid runs instead of pixel by
pixel). With --preview FILE.ppm it also renders every picture to a sheet."""
import sys

RGB = [(0,0,0),(0,0,170),(0,170,0),(0,170,170),(170,0,0),(170,0,170),(170,85,0),
       (170,170,170),(85,85,85),(85,85,255),(85,255,85),(85,255,255),(255,85,85),
       (255,85,255),(255,255,85),(255,255,255)]

def parse(path):
    items, cur = [], None
    for ln in open(path):
        ln = ln.rstrip("\n")
        if ln.startswith("#") and cur is None:
            continue
        if ln.startswith("@"):
            kind, name = ln[1:].split()
            cur = {"kind": kind, "name": name, "rows": []}
            items.append(cur)
        elif ln.strip() == "" or ln.startswith("#"):
            cur = None
        elif cur is not None:
            cur["rows"].append(ln)
    for it in items:
        w = max(len(r) for r in it["rows"])
        for i, r in enumerate(it["rows"]):
            if len(r) != w:
                sys.exit("%s row %d: width %d, expected %d" % (it["name"], i, len(r), w))
        it["w"], it["h"] = w, len(it["rows"])
        if it["kind"] in ("spr", "gun") and w % 2:
            sys.exit("%s: odd width" % it["name"])
    return items

def sprite_runs(it):
    """Per byte column: list of (len, value, keepmask). keepmask 0xFF = clear.
    Stored as len, keepmask, even-row byte, odd-row byte (see fastcol.asm)."""
    cols = []
    for bx in range(it["w"] // 2):
        texels = []
        for r in it["rows"]:
            a, b = r[2 * bx], r[2 * bx + 1]
            val = (0 if a == "." else int(a, 16)) << 4 | (0 if b == "." else int(b, 16))
            mask = (0xF0 if a == "." else 0) | (0x0F if b == "." else 0)
            texels.append((val, mask))
        runs = []
        for t in texels:
            if runs and tuple(runs[-1][1:]) == t and runs[-1][0] < 255:
                runs[-1][0] += 1
            elif runs and t[1] == 0xFF and runs[-1][2] == 0xFF:
                runs[-1][0] += 1
            else:
                runs.append([1, t[0] if t[1] != 0xFF else 0, t[1]])
        while runs and runs[-1][2] == 0xFF:  # trailing clear runs are implicit
            runs.pop()
        cols.append(runs)
    return cols

def pixel_runs(it):
    """World sprites are scaled, so each screen byte shows one art pixel:
    one run list per pixel column, value = color in both nibbles."""
    cols = []
    for x in range(it["w"]):
        runs = []
        for r in it["rows"]:
            c = r[x]
            t = (0, 0xFF) if c == "." else (int(c, 16) * 0x11, 0)
            if runs and (runs[-1][1], runs[-1][2]) == t and runs[-1][0] < 255:
                runs[-1][0] += 1
            else:
                runs.append([1, t[0], t[1]])
        while runs and runs[-1][2] == 0xFF:
            runs.pop()
        cols.append(runs)
    return cols

def tex_runs(it):
    cols = []
    for x in range(it["w"]):
        runs = []
        for r in it["rows"]:
            t = int(r[x])
            if runs and runs[-1][1] == t:
                runs[-1][0] += 1
            else:
                runs.append([1, t])
        cols.append(runs)
    return cols

def main():
    items = parse("art.txt")
    o = ["/* Generated by mkart.py from art.txt. Do not edit. */",
         '#include "jrdoom.h"', ""]
    sprs, texs, pics = [], [], []
    for it in items:
        n = it["name"]
        if it["kind"] in ("spr", "gun"):
            cols = pixel_runs(it) if it["kind"] == "spr" else sprite_runs(it)
            data, ofs = [], []
            for c in cols:
                ofs.append(len(data))
                for ln, v, m in c:
                    data += [ln, m, v, v]
                data.append(0)
            o.append("static const unsigned char %s_d[%d] = {%s};" % (n, len(data), ",".join(map(str, data))))
            o.append("static const unsigned short %s_o[%d] = {%s};" % (n, len(ofs), ",".join(map(str, ofs))))
            sprs.append((n, it))
            if it["kind"] == "gun":   # also as plain pixels, for fx_compile
                px = []
                for r in it["rows"]:
                    px += [255 if c == "." else int(c, 16) for c in r]
                o.append("const unsigned char gunpix_%s[%d] = {%s};" % (n, len(px), ",".join(map(str, px))))
                pics.append(("gunpix_" + n, it))
        elif it["kind"] == "tex":
            cols = tex_runs(it)
            data, ofs = [], []
            for c in cols:
                ofs.append(len(data))
                for ln, t in c:
                    data += [ln, t]
                data.append(0)
            o.append("static const unsigned char %s_t[%d] = {%s};" % (n, len(data), ",".join(map(str, data))))
            o.append("static const unsigned short %s_to[16] = {%s};" % (n, ",".join(map(str, ofs))))
            texs.append(n)
        elif it["kind"] == "pic":
            px = []
            for r in it["rows"]:
                px += [255 if c == "." else int(c, 16) for c in r]
            o.append("const unsigned char pic_%s[%d] = {%s};" % (n, len(px), ",".join(map(str, px))))
            pics.append((n, it))
    o.append("")
    o.append("const Sprite sprites[NUM_SPRITES] = {")
    for n, it in sprs:
        w = it["w"] if it["kind"] == "spr" else it["w"] // 2
        o.append("  {%d, %d, %s_o, %s_d}, /* %s */" % (w, it["h"], n, n, n))
    o.append("};")
    o.append("const Texture textures[NUM_TEXTURES] = {")
    for n in texs:
        o.append("  {%s_to, %s_t}," % (n, n))
    o.append("};")
    open("artdata.c", "w").write("\n".join(o) + "\n")
    h = ["/* Generated by mkart.py. Do not edit. */"]
    for i, (n, it) in enumerate(sprs):
        h.append("#define SPR_%s %d" % (n.upper(), i))
    h.append("#define NUM_SPRITES %d" % len(sprs))
    for i, n in enumerate(texs):
        h.append("#define TEX_%s %d" % (n.upper(), i))
    h.append("#define NUM_TEXTURES %d" % len(texs))
    for n, it in pics:
        if n.startswith("gunpix_"):
            h.append("extern const unsigned char %s[%d]; /* %dx%d */" % (n, it["w"] * it["h"], it["w"], it["h"]))
            continue
        h.append("extern const unsigned char pic_%s[%d]; /* %dx%d */" % (n, it["w"] * it["h"], it["w"], it["h"]))
        h.append("#define PIC_%s_W %d" % (n.upper(), it["w"]))
        h.append("#define PIC_%s_H %d" % (n.upper(), it["h"]))
    open("artids.h", "w").write("\n".join(h) + "\n")

    if len(sys.argv) > 2 and sys.argv[1] == "--preview":
        S = 4
        tiles = []
        for it in items:
            sx = S if it["kind"] == "spr" else (S * 5 // 3 if it["kind"] in ("gun", "pic") else S * 2)
            img = []
            for r in it["rows"]:
                line = []
                for c in r:
                    if it["kind"] == "tex":
                        col = [(200,200,200),(150,150,150),(100,100,100),(50,50,50)][int(c)]
                    else:
                        col = (40, 0, 60) if c == "." else RGB[int(c, 16)]
                    line += [col] * sx
                for _ in range(S if it["kind"] != "tex" else S * 2):
                    img.append(line)
            tiles.append(img)
        W = 1200
        rows, row, x, H = [], [], 0, 0
        for t in tiles:
            if x + len(t[0]) + 8 > W:
                rows.append(row); row, x = [], 0
            row.append(t); x += len(t[0]) + 8
        rows.append(row)
        out = []
        for row in rows:
            h = max(len(t) for t in row) + 8
            for y in range(h):
                line = []
                for t in row:
                    seg = t[y] if y < len(t) else [(20,20,20)] * len(t[0])
                    line += seg + [(20,20,20)] * 8
                line += [(20,20,20)] * (W - len(line))
                out.append(line[:W])
        with open(sys.argv[2], "wb") as f:
            f.write(b"P6\n%d %d\n255\n" % (W, len(out)))
            for line in out:
                f.write(bytes(v for p in line for v in p))

main()
